"""Классификация обращений по ключевым словам.

Определяет категорию сообщения (F3) и причину, по которой его нужно передать человеку (F4).
Позже часть этой работы возьмёт на себя нейросеть, а этот модуль останется
страховкой: важные решения (жалоба, отказ, попытка обойти правила) принимаются кодом.
"""

import re

# Пять категорий из ТЗ
KNOWLEDGE = "вопрос по базе знаний"
REQUEST = "заявка"
COMPLAINT = "жалоба"
SOLVE_TASK = "просьба решить задание"
OFF_TOPIC = "непонятно / вне темы"

# Ключевые слова для каждого случая. Пишем начало слова, чтобы ловить все формы:
# «жалоб» найдёт «жалоба», «жалобу», «жалобой».
INJECTION_WORDS = [
    "забудь", "игнорируй", "инструкци", "системн", "промпт", "притворись",
    "ты администратор", "ты теперь", "режим разработчика", "отключи правила",
]
DANGER_WORDS = [
    "травл", "травят", "травит", "затравил", "угрожа", "угроз", "издева", "обижают",
    "бьют", "избива", "буллинг", "шантаж",
    "покончить с собой", "не хочу жить", "суицид",
]
SOLVE_WORDS = [
    "реши ", "решите", "реши мне", "решить за меня", "сделай за меня", "сделайте за меня",
    "дай ответ", "дай ответы", "скажи ответ", "ответы на контрольн", "ответ на задани",
    "ответы к", "напиши сочинение",
]
MONEY_WORDS = [
    "деньг", "возврат", "верните", "списал", "списани", "дважды оплат", "двойн",
]
COMPLAINT_WORDS = [
    "жалоб", "несправедлив", "нечестн", "не согласен", "не согласна", "возмущ",
    "перепровер", "не начислил", "не пришли", "обманул",
]
EXCEPTION_WORDS = [
    "продлите", "продли мне", "измените мне", "исправьте мне", "поставьте мне",
    "добавьте мне балл", "верните мне балл", "пересдать", "пересдач",
]
TECH_WORDS = [
    "выкинул", "вылетел", "вылетает", "завис", "сбой", "не загружа", "не открыва",
    "не работает", "ошибка", "не грузит", "сломал",
]
# Слова, по которым понятно, что вопрос про платформу (нужно для случая «не уверен»)
PLATFORM_WORDS = [
    "балл", "дедлайн", "дз", "домашк", "домашн", "контрольн", "курс", "подписк",
    "тариф", "учител", "класс", "оплат", "чек", "урок", "задани", "профил",
    "пароль", "аккаунт", "подарочк", "бонус", "практик",
]


def contains_any(text, words):
    """Проверяет, есть ли в тексте хотя бы одно слово из списка."""
    return any(word in text for word in words)


def normalize(message):
    """Приводит текст к нижнему регистру и меняет «ё» на «е», чтобы проще искать слова."""
    text = message.lower().replace("ё", "е")
    text = re.sub(r"\s+", " ", text)  # несколько пробелов подряд → один
    return " " + text + " "  # пробелы по краям, чтобы «реши » находилось и в конце фразы


def classify(message):
    """Возвращает словарь: категория и особый случай (если есть).

    Особые случаи (special):
      "injection"  — попытка обойти правила → отказ
      "danger"     — травля, угрозы, опасность → совет и передача человеку
      "money"      — деньги → передать в поддержку
      "exception"  — просьба-исключение (баллы, дедлайн, пересдача) → передать учителю
      None         — особого случая нет
    """
    text = normalize(message)

    if contains_any(text, INJECTION_WORDS):
        return {"category": OFF_TOPIC, "special": "injection"}
    if contains_any(text, DANGER_WORDS):
        return {"category": COMPLAINT, "special": "danger"}
    if contains_any(text, SOLVE_WORDS):
        return {"category": SOLVE_TASK, "special": None}
    if contains_any(text, MONEY_WORDS):
        return {"category": COMPLAINT, "special": "money"}
    if contains_any(text, EXCEPTION_WORDS):
        return {"category": REQUEST, "special": "exception"}
    if contains_any(text, COMPLAINT_WORDS):
        return {"category": COMPLAINT, "special": None}
    if contains_any(text, TECH_WORDS):
        return {"category": REQUEST, "special": None}
    return {"category": KNOWLEDGE, "special": None}


def is_about_platform(message):
    """True, если в сообщении есть слова про платформу (баллы, курсы, контрольные…)."""
    return contains_any(normalize(message), PLATFORM_WORDS)
